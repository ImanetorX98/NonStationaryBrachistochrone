def write_manifest() -> int:
    missing = 0
    lines = ["# artefact\tcommand\tpath\tsha256"]
    for artefact, command, path in MANIFEST:
        p = ROOT / path
        if not p.exists():
            lines.append(f"{artefact}\t{command}\t{path}\tMISSING")
            missing += 1
            continue
        lines.append(f"{artefact}\t{command}\t{path}\t{sha256(p)}")
    (HERE / "MANIFEST.tsv").write_text("\n".join(lines) + "\n")
    return missing


# --------------------------------------------------------------------------
# LaTeX fragment
# --------------------------------------------------------------------------
def tex_escape(s: str) -> str:
    return s.replace("_", r"\_")


def write_tex(data: dict) -> None:
    v = data["validation"]
    e = data["exact"]
    win = data["epsilon_window"]
    sep = data["loci"]
    lo, hi = sep["fit_interval_r_over_M"]

    exact_slopes = [r["exact_slope"] for r in v["rows"]]
    exact_sigmas = [r["exact_sigma"] for r in v["rows"]]
    common = (max(exact_slopes) - min(exact_slopes)) < 1e-9
    if common:
        slope_str = f"${exact_slopes[0]:.2f}\\pm{exact_sigmas[0]:.2f}$"
    else:
        slope_str = (f"${min(exact_slopes):.2f}$--${max(exact_slopes):.2f}$")

    lead = [r["leading_slope"] for r in v["rows"]]

    out = [
        "% ---------------------------------------------------------------",
        "% GENERATED FILE -- do not edit by hand.",
        "% Produced by paper2/provenance/make_provenance.py; see that file for",
        "% why these numbers are generated rather than transcribed",
        "% (CQG-116884, referee major comments 7 and 10).",
        f"% generated {data['generated_utc']}",
        "% ---------------------------------------------------------------",
        r"\newcommand{\provEpsWindow}{$\varepsilon\in\{"
        + ",\\,".join(f"{x:g}" for x in win) + r"\}$}",
        r"\newcommand{\provFitInterval}{$r/M\in[" + f"{lo:g},{hi:g}" + r"]$}",
        r"\newcommand{\provLocusSep}{"
        + f"{sep['min_separation_r_over_M']:g}" + r"\,M}",
        r"\newcommand{\provExactSlope}{" + slope_str + r"}",
        r"\newcommand{\provLeadSlope}{$"
        + f"{min(lead):.2f}" + r"$--$" + f"{max(lead):.2f}" + r"$}",
        r"\newcommand{\provExactRunSlope}{$" + f"{e['slope']:.2f}" + r"$}",
        r"\newcommand{\provExactRunResidual}{$" + f"{e['residual']:.2e}"
        .replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + r"}$}",
        "",
        "% per-configuration rows of the validation run",
        r"\newcommand{\provValidationRows}{%",
    ]
    for r in v["rows"]:
        out.append(
            f"  {r['config']} & ${r['leading_slope']:.2f}\\pm"
            f"{r['leading_sigma']:.2f}$ & ${r['exact_slope']:.2f}\\pm"
            f"{r['exact_sigma']:.2f}$ \\\\")
    out.append("}")
    out.append("")
    sub = data.get("subwindow", {})
    if sub.get("available"):
        seqs = [" \\to ".join(f"{f['slope']:.3f}" for f in c["fits"])
                for c in sub["configs"]]
        out.append("% fitted exponent on shrinking epsilon sub-windows")
        out.append(r"\newcommand{\provSubwindowDrift}{$" + seqs[0] + r"$}")
        narrow = max(abs(c["slope_narrowest"] - 2.0) for c in sub["configs"])
        out.append(r"\newcommand{\provSubwindowNarrowest}{$"
                   + f"{2.0 + narrow:.3f}" + r"$}")
        # no math delimiters: the manuscript uses this inside $...$
        out.append(r"\newcommand{\provSubwindowEpsMax}{"
                   + f"{sub['configs'][0]['fits'][-1]['eps_max']:g}" + r"}")
        out.append("")
    out.append("% SHA-256 (first 12 hex) of every script behind the table")
    for name, h in data["hashes"].items():
        macro = "".join(w.capitalize() for w in
                        re.split(r"[^A-Za-z]+", Path(name).stem) if w)
        out.append(r"\newcommand{\provHash" + macro + r"}{\texttt{" + h + "}}")
    out.append("")
    out.append(r"\newcommand{\provHashLine}{%")
    items = [r"\texttt{" + tex_escape(Path(n).name) + r"}\,$=$\,\texttt{"
             + h + "}" for n, h in data["hashes"].items()]
    out.append("  SHA-256 (first 12 hex): " + ";\n  ".join(items) + ".}")
    (HERE / "adiabatic_slopes.tex").write_text("\n".join(out) + "\n")


# --------------------------------------------------------------------------
# main
# --------------------------------------------------------------------------
def main(argv: list[str]) -> int:
    manifest_only = "--manifest" in argv
    check = "--check" in argv

    print("== manifest ==")
    missing = write_manifest()
    print(f"   {len(MANIFEST)} artefacts, {missing} missing "
          f"-> {rel(HERE / 'MANIFEST.tsv')}")
    if manifest_only:
        return 1 if missing else 0

    print("== adiabatic validation (one command, one dataset) ==")
    win = epsilon_window()
    print(f"   epsilon window: {win}")

    out_v, dt_v = run(VALIDATION)
    rows = parse_validation(out_v)
    print(f"   {VALIDATION.name}: {len(rows)} configurations, {dt_v:.0f}s")
    for r in rows:
        print(f"     {r['config'][:44]:44s} "
              f"leading {r['leading_slope']:.2f}+/-{r['leading_sigma']:.2f}  "
              f"exact {r['exact_slope']:.2f}+/-{r['exact_sigma']:.2f}")

    out_e, dt_e = run(EXACT)
    ex = parse_exact(out_e)
    print(f"   {EXACT.name}: slope {ex['slope']:.2f}"
          + (f" (robust {ex['robust_slope']:.2f})"
             if ex["robust_slope"] else "")
          + f", residual {ex['residual']:.2e} at eps={ex['residual_at']}"
          + f", {dt_e:.0f}s")

    sep = locus_separation()
    print(f"   fit interval r/M = {sep['fit_interval_r_over_M']}, "
          f"nearest excluded locus {sep['min_separation_r_over_M']:g} M away")

    hashes = {}
    for _, _, path in MANIFEST:
        p = ROOT / path
        if p.exists() and p.suffix == ".py" and "ThakurtaMetric" in path:
            hashes[path] = short(p)

    data = {
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "epsilon_window": win,
        "validation": {"script": rel(VALIDATION), "rows": rows,
                       "seconds": round(dt_v, 1)},
        "exact": {"script": rel(EXACT), **ex, "seconds": round(dt_e, 1)},
        "loci": sep,
        "hashes": hashes,
    }
    (HERE / "adiabatic_slopes.json").write_text(json.dumps(data, indent=2) + "\n")
    write_tex(data)
    print(f"   wrote {rel(HERE / 'adiabatic_slopes.json')}")
    print(f"   wrote {rel(HERE / 'adiabatic_slopes.tex')}")

    sub = subwindow_drift()
    data["subwindow"] = sub
    (HERE / "adiabatic_slopes.json").write_text(json.dumps(data, indent=2) + "\n")
    write_tex(data)

    ok = report_subwindow(sub)
    return 1 if (missing or (check and not ok)) else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
